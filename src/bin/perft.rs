//! Perft driver — the Phase 1 gate.
//!
//!   perft [depth] [--fen "<fen>"] [--divide]
//!   perft --suite tests/perft_suite.txt
//!
//! Output is `depth<TAB>nodes` (or `label<TAB>depth<TAB>nodes` for a suite), so it
//! diffs byte-for-byte against `python ref/reference.py` with the same arguments.

use bschess::perft::{perft_divide, perft_parallel};
use bschess::position::Position;

fn run_suite(path: &str) {
    let text = match std::fs::read_to_string(path) {
        Ok(t) => t,
        Err(e) => {
            eprintln!("cannot read {path}: {e}");
            std::process::exit(2);
        }
    };
    // Strip a UTF-8 BOM: suite files generated by redirecting Windows console
    // output pick one up, and it would otherwise land in the first depth field.
    let text = text.strip_prefix('\u{feff}').unwrap_or(&text);
    for line in text.lines() {
        let line = line.trim_end_matches(['\r', '\n']);
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 3 {
            eprintln!("malformed suite line (need depth<TAB>fen<TAB>label): {line}");
            std::process::exit(2);
        }
        let max_depth: u32 = fields[0].parse().expect("bad depth in suite file");
        let pos = match Position::from_fen(fields[1]) {
            Ok(p) => p,
            Err(e) => {
                eprintln!("bad FEN for {}: {e}", fields[2]);
                std::process::exit(2);
            }
        };
        for d in 1..=max_depth {
            let t = std::time::Instant::now();
            let n = perft_parallel(&pos, d);
            println!("{}\t{d}\t{n}", fields[2]);
            eprintln!(
                "  {:<22} depth {d}: {n:>12} nodes  {:>6.1}s",
                fields[2],
                t.elapsed().as_secs_f64()
            );
        }
    }
}

/// Emit a suite file of random reachable positions. A handful of curated
/// positions only proves the rules you thought to test; random positions drawn
/// from real play find the interactions you did not think of.
///
/// Both engines bulk-count at depth 1, so the cost of one position is
/// `width^(depth-1)` movegen calls, not `width^depth`. Depth is chosen per
/// position from that budget: sparse positions go deep, crowded ones stay
/// shallow, and the total stays predictable on the Python side.
fn emit_random_suite(count: usize, max_depth: u32, seed: u64) {
    use bschess::movegen::{generate_vec, GenMode};
    use bschess::tables::SplitMix64;

    const BUDGET: f64 = 50_000.0;
    let mut rng = SplitMix64::new(seed);
    let mut emitted = 0;
    let mut attempts = 0;
    let mut histogram = [0usize; 8];

    while emitted < count && attempts < count * 50 {
        attempts += 1;
        let mut pos = Position::startpos();
        // Spread the walk length widely: short games leave crowded boards (wide,
        // shallow), long ones leave sparse boards (narrow, deep). Both matter.
        let plies = 2 + rng.below(90);
        for _ in 0..plies {
            if pos.result().is_some() {
                break;
            }
            let moves = generate_vec(&pos, GenMode::All);
            pos.make_move(moves[rng.below(moves.len())]);
        }
        if pos.result().is_some() {
            continue;
        }
        let width = generate_vec(&pos, GenMode::All).len() as f64;
        let depth = (2..=max_depth)
            .filter(|&d| width.powi(d as i32 - 1) <= BUDGET)
            .max()
            .unwrap_or(2);
        println!("{depth}\t{}\trandom-{emitted:03}", pos.to_fen());
        histogram[depth.min(7) as usize] += 1;
        emitted += 1;
    }
    eprintln!("emitted {emitted} positions ({attempts} attempts)");
    for (d, n) in histogram.iter().enumerate() {
        if *n > 0 {
            eprintln!("  depth {d}: {n} positions");
        }
    }
}

fn main() {
    bschess::init();
    let args: Vec<String> = std::env::args().skip(1).collect();

    let mut depth = 4u32;
    let mut fen = String::new();
    let mut divide = false;
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--fen" => {
                i += 1;
                fen = args.get(i).cloned().unwrap_or_default();
            }
            "--suite" => {
                i += 1;
                run_suite(args.get(i).map(|s| s.as_str()).unwrap_or("tests/perft_suite.txt"));
                return;
            }
            "--random" => {
                let n: usize = args.get(i + 1).and_then(|s| s.parse().ok()).unwrap_or(100);
                let d: u32 = args.get(i + 2).and_then(|s| s.parse().ok()).unwrap_or(3);
                let seed: u64 = args.get(i + 3).and_then(|s| s.parse().ok()).unwrap_or(1);
                emit_random_suite(n, d, seed);
                return;
            }
            "--divide" => divide = true,
            other => {
                if let Ok(d) = other.parse::<u32>() {
                    depth = d;
                }
            }
        }
        i += 1;
    }

    let pos = if fen.is_empty() {
        Position::startpos()
    } else {
        match Position::from_fen(&fen) {
            Ok(p) => p,
            Err(e) => {
                eprintln!("bad FEN: {e}");
                std::process::exit(2);
            }
        }
    };

    eprintln!("{}", pos.board_string());
    eprintln!("fen {}", pos.to_fen());

    if divide {
        for (m, n) in perft_divide(&pos, depth) {
            println!("{m}\t{n}");
        }
        return;
    }

    for d in 1..=depth {
        let t = std::time::Instant::now();
        let n = perft_parallel(&pos, d);
        let ms = t.elapsed().as_millis();
        println!("{d}\t{n}");
        eprintln!("  depth {d}: {n} nodes in {ms} ms");
    }
}
